#!/usr/bin/env python3
"""Render the oracle's ground truth for a subject as a reader-checkable table.

    python3 bench/expected.py --language typescript torture > typescript/subjects/torture/EXPECTED.md

A torture subject is only useful if a reader can look at each construct and confirm what the
oracle says about it BEFORE trusting the same oracle on 35,000 sites of apache-ant. This prints,
per source file, every scored call site: where it is, who the caller is, what is called, the
declared target, the envelope, and the verdict a tool earns for each answer. It is generated from
`.work/<lang>/<subject>/gt.sites.jsonl`, so it cannot disagree with what the scorer uses.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def short(ref: str, lang: str) -> str:
    """`pkg.Outer.Inner#m(int)` -> `Inner#m(int)`; `src/x.ts:Cls#m()` -> `Cls#m()`; `src/x.ts#f()` -> `x#f()`."""
    t, sep, m = ref.partition("#")
    if lang == "typescript":
        mod, colon, decl = t.partition(":")
        t = decl if colon else mod.rsplit("/", 1)[-1].rsplit(".", 1)[0]
    else:
        t = t.rsplit(".", 1)[-1]
    return f"{t}#{m}" if sep else t


def file_of(caller: str, lang: str) -> str:
    t = caller.partition("#")[0]
    if lang == "typescript":
        return t.partition(":")[0]
    return t.rsplit(".", 1)[0] if "." in t else t


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("subject")
    ap.add_argument("--language", default="java")
    a = ap.parse_args()
    W = ROOT / ".work" / a.language / a.subject
    sites = [json.loads(l) for l in (W / "gt.sites.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    excluded = (W / "gt.excluded.txt").read_text(encoding="utf-8").splitlines() if (W / "gt.excluded.txt").exists() else []

    by_file: dict[str, list[dict]] = defaultdict(list)
    for s in sites:
        by_file[file_of(s["caller"], a.language)].append(s)

    out = [f"# Expected ground truth — `{a.subject}` ({a.language})", "",
           "Generated by `bench/expected.py` from the oracle's site records; do not edit. One row per call",
           "site the oracle recorded. `kind`: `internal` is scored; `boundary` has no application target",
           "(not scored); `indirect` is a call through a function value (neutral, never scored).",
           "`verdict for` shows what each answer earns on a uniquely-linked group.", ""]
    n_scored = sum(1 for s in sites if s["kind"] == "internal")
    out.append(f"{len(sites)} sites · {n_scored} scored · "
               f"{sum(1 for s in sites if s['kind'] == 'boundary')} boundary · "
               f"{sum(1 for s in sites if s['kind'] == 'indirect')} indirect · "
               f"{len(excluded)} exclusion records")
    out.append("")
    for f in sorted(by_file):
        out.append(f"## `{f}`")
        out.append("")
        out.append("| line | caller | calls | kind | declared target (certain) | envelope (possible) | verdict for |")
        out.append("|---:|---|---|---|---|---|---|")
        for s in sorted(by_file[f], key=lambda x: (x["line"], x["seq"])):
            cert = ", ".join(short(x, a.language) for x in s["certain"]) or "—"
            poss = s["possible"]
            envelope = ", ".join(short(x, a.language) for x in poss) or "—"
            anc = s.get("declaring_ancestors") or []
            if s["kind"] != "internal":
                verdict = "not scored"
            elif len(poss) == 1:
                verdict = f"`{short(poss[0], a.language)}` → exact"
                if anc:
                    verdict += f"; `{short(anc[0], a.language)}` → ancestor"
                verdict += "; anything else → wrong"
            else:
                verdict = f"ambiguous group ({len(poss)} targets): one → exact, all → over_fan"
            out.append(f"| {s['line']} | `{short(s['caller'], a.language)}` | `{s['callee_name']}` | {s['kind']} | "
                       f"{cert} | {envelope} | {verdict} |")
        out.append("")
    if excluded:
        out.append("## Exclusions applied to both sides")
        out.append("")
        out.append("```")
        out.extend(excluded[:200])
        if len(excluded) > 200:
            out.append(f"… {len(excluded) - 200} more")
        out.append("```")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
